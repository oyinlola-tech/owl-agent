import { useCallback, useEffect, useState } from "react";
import { Globe, LockKey, ShieldCheck, ShieldWarning, WifiSlash } from "@phosphor-icons/react";
import { agentApi, isServiceAuthError } from "../../../../services/agentApi.service";
import type { SecurityStatusRead } from "../../../../services/agentApi.types";
import { Tag } from "../../../../../shared/components/tag.component";
import { SettingValueRow } from "../settingRow.component";

type SecurityStatusLoad =
  | { state: "loading" }
  | { state: "ready"; status: SecurityStatusRead }
  | { state: "offline" }
  | { state: "unauthorized" };

const SANDBOX_BACKEND_NAMES: Record<string, string> = {
  bubblewrap: "Bubblewrap (Linux namespaces)",
  "sandbox-exec": "macOS sandbox profile",
  docker: "Docker container",
  podman: "Podman container",
};

const TOKEN_SOURCE_TEXT: Record<string, string> = {
  env: "Handed to the service by the desktop app at launch",
  file: "Read from the token file set with OWL_SERVICE_TOKEN_FILE",
  generated: "Generated by the service when it started",
};

function describeSelfTest(selfTest: SecurityStatusRead["sandbox"]["self_test"]): string {
  if (!selfTest.ran) return selfTest.detail || "The self-test did not run because no sandbox is available.";
  const checks = [
    `reading outside the workspace ${selfTest.read_outside_blocked ? "was blocked" : "was NOT blocked"}`,
    `opening a network socket ${selfTest.network_blocked ? "was blocked" : "was NOT blocked"}`,
    `writing inside the workspace ${selfTest.workspace_write_ok ? "worked" : "failed"}`,
  ];
  return `At startup, ${checks.join(", ")}.`;
}

function useSecurityStatus() {
  const [load, setLoad] = useState<SecurityStatusLoad>({ state: "loading" });
  const reload = useCallback(async () => {
    setLoad({ state: "loading" });
    try {
      setLoad({ state: "ready", status: await agentApi.securityStatus() });
    } catch (error) {
      setLoad({ state: isServiceAuthError(error) ? "unauthorized" : "offline" });
    }
  }, []);
  useEffect(() => { void reload(); }, [reload]);
  return { load, reload };
}

function SecurityStatusUnavailable({ load, onRetry }: { load: SecurityStatusLoad; onRetry: () => void }) {
  if (load.state === "loading") return <p className="pg-p pg-muted" role="status">Reading the live security status…</p>;
  const message = load.state === "unauthorized"
    ? "Can't authenticate with the local OWL service, so its security status can't be read."
    : "The OWL service is offline, so the live sandbox and token status can't be shown. Start the service to see them.";
  return (
    <div className="callout orange" role="status">
      <WifiSlash size={18} weight="duotone" color="var(--orange)" />
      <span>{message} <button className="pg-link" onClick={onRetry}>Retry</button></span>
    </div>
  );
}

function SandboxStatusGroup({ status }: { status: SecurityStatusRead }) {
  const { sandbox } = status;
  const backendName = SANDBOX_BACKEND_NAMES[sandbox.backend] ?? (sandbox.backend === "none" ? "None" : sandbox.backend);
  const limits = sandbox.limits;
  return (
    <div className="surface pg-setgroup">
      <h4>Command sandbox</h4>
      <SettingValueRow title={`Sandbox: ${backendName}`}
        sub={sandbox.active ? `Every command OWL runs goes through it (mode: ${sandbox.mode}).` : `Commands run without a sandbox: ${sandbox.reason || "no backend available"} (mode: ${sandbox.mode}).`}>
        {sandbox.active ? <Tag hue="green" icon={ShieldCheck}>Active</Tag> : <Tag hue="red" icon={ShieldWarning}>Not active</Tag>}
      </SettingValueRow>
      <SettingValueRow title="Startup self-test" sub={describeSelfTest(sandbox.self_test)}>
        {sandbox.self_test.passed ? <Tag hue="green">Passed</Tag> : <Tag hue={sandbox.self_test.ran ? "red" : "gray"}>{sandbox.self_test.ran ? "Failed" : "Not run"}</Tag>}
      </SettingValueRow>
      <SettingValueRow title="Network for commands" sub={`Commands: ${sandbox.network_policy.commands}. Verification: ${sandbox.network_policy.verification}.`}>
        <span className="pg-mono">{sandbox.network_policy.default}</span>
      </SettingValueRow>
      <SettingValueRow title="Process limits" sub="Each sandboxed command is stopped if it goes past these.">
        <span className="pg-mono">{limits.max_processes} processes · {limits.cpu_seconds}s CPU · {limits.memory_mb} MB · {limits.open_files} files</span>
      </SettingValueRow>
      {sandbox.protected.length > 0 && (
        <div className="pg-chips" aria-label="Protected by the sandbox">{sandbox.protected.map((item) => <Tag key={item} hue="blue" icon={LockKey}>{item}</Tag>)}</div>
      )}
    </div>
  );
}

function ServiceAccessGroup({ status }: { status: SecurityStatusRead }) {
  const token = status.service_token;
  return (
    <div className="surface pg-setgroup">
      <h4>Service access</h4>
      <SettingValueRow title="Token protection" sub={`Every request except the health check needs this app's token. ${TOKEN_SOURCE_TEXT[token.source] ?? token.source}.`}>
        <Tag hue={token.required ? "green" : "red"} icon={LockKey}>{token.required ? "On" : "Off"}</Tag>
      </SettingValueRow>
      {token.dev_token_accepted && (
        <SettingValueRow title="Development token" sub="The service also accepts OWL_DEV_TOKEN. Fine for development, don't use it for daily work.">
          <Tag hue="orange">Accepted</Tag>
        </SettingValueRow>
      )}
      <SettingValueRow title="Who can connect" sub={`Requests must come to ${token.host_check} addresses${token.json_required_for_changes ? ", and changes must be sent as JSON" : ""}, so websites can't reach the service.`}>
        <Tag hue="green" icon={ShieldCheck}>Enforced</Tag>
      </SettingValueRow>
      <SettingValueRow title="Browser blocklist" sub={`The browser tool only opens ${status.browser.schemes.join(" and ")} pages and never these addresses.`}>
        <Globe size={16} />
      </SettingValueRow>
      <div className="pg-chips" aria-label="Blocked browser addresses">{status.browser.blocked.map((item) => <Tag key={item} hue="red">{item}</Tag>)}</div>
    </div>
  );
}

export function SecurityStatusSection() {
  const { load, reload } = useSecurityStatus();
  if (load.state !== "ready") {
    return (
      <div className="surface pg-setgroup">
        <h4>Command sandbox</h4>
        <SecurityStatusUnavailable load={load} onRetry={() => void reload()} />
      </div>
    );
  }
  return (
    <>
      <SandboxStatusGroup status={load.status} />
      <ServiceAccessGroup status={load.status} />
    </>
  );
}
